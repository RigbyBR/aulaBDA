SET client_encoding TO 'UTF8';

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY, 
    nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(11) NOT NULL,
    telefone VARCHAR(15),
    email VARCHAR(100),
    CONSTRAINT pk_cliente PRIMARY KEY(id_cliente), 
    CONSTRAINT uq_clinte_cpf UNIQUE(cpf),
    CONSTRAINT ck_cliente_cpf CHECK(cpf ~ '^[0-9]{11}$')
);

CREATE TABLE categoria_veiculo (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(30) NOT NULL,
    valor_hora NUMERIC(8,2) NOT NULL,
    valor_maximo_diario NUMERIC(8,2) NOT NULL,
    CONSTRAINT pk_categoria_veiculo PRIMARY KEY(id_categoria),
    CONSTRAINT uq_categoria_nome UNIQUE(nome),
    CONSTRAINT ck_categria_valor_hora CHECK(valor_hora > 0),
    CONSTRAINT ck_categoria_valor_max CHECK(valor_maximo_diario >= valor_hora)
);

CREATE TABLE vaga (
    id_vaga INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(5) NOT NULL, -- EX: A01, C08
    setor CHAR(1) NOT NULL,
    tipo VARCHAR(15) NOT NULL DEFAULT 'COMUM',
    ativa BOOLEAN NOT NULL DEFAULT TRUE, -- FALSE = interditada/manutenção
    CONSTRAINT pk_vaga PRIMARY KEY(id_vaga),
    CONSTRAINT uq_vaga_codigo UNIQUE(codigo),
    CONSTRAINT ck_vaga_setor CHECK(setor IN ('A','B','C')),
    CONSTRAINT ck_vaga_tipo CHECK(tipo IN ('COMUM','COBERTA','PREFERENCIAL','MOTO','ELETRICA'))
);

CREATE TABLE veiculo (
    id_veiculo IDENTITY GENERATED BY DEFAULT AS IDENTITY,
    placa VARCHAR(7) NOT NULL, -- EX: BNH2087
    modelo VARCHAR(50) NOT NULL,
    cor VARCHAR(20),
    id_cliente INTEGER NOT NULL,
    id_categoria INTEGER NOT NULL,
    CONSTRAINT pk_veiculo PRIMARY KEY(id_veiculo),
    CONSTRAINT uq_veiculo_placa UNIQUE (placa)
    CONSTRAINT ck_veiculo_placa CHECK (placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_veiculo_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria_veiculo(id_categoria)
        ON DELETE RESTRICT ON UPDATE CASCADE    
);

CREATE TABLE estadia (
    id_estadia INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_veiculo INTEGER NOT NULL,
    id_vaga INTEGER NOT NULL
    data_entrada TIMESTAMP NOT NULL DEFAULT CORRENT_TIMESTAMP,
    data_saida TIMESTAMP,
    valor_total NUMERIC(8,2),
    CONSTRAINT pk_estadia PRIMARY KEY(id_estadia),
    CONSTRAINT fk_estadia_veiculo FOREIGN KEY(id_veiculo)
        REFERENCES veiculo (id_veiculo)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_estadia_vaga FOREIGN KEY(id_vaga)
        REFERENCES vaga(id_vaga)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_estadia_periodo CHECK (data_saida IS NULL OR data_saida > data_entrada),
    CONSTRAINT ck_estadia_valor CHECK (valor_total => 0),
    CONSTRAINT ck_estadia_fechamento CHECK (
        (data_saida IS NULL AND valor_total IS NULL) OR
        (data_saida IS NULL AND valor_total IS NOT NULL)
    )        
);

CREATE TABLE pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_estadia INTEGER NOT NULL,
    forma_pagamento VARCHAR(15) NOT NULL,
    valor_pago NUMERIC(8,2) NOT NULL,
    data_pagamento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_pagamento PRIMARY KEY(id_pagamento),
    CONSTRAINT uq_pagamento_estadia UNIQUE (id_estadia),
    CONSTRAINT fk_pagamento_estadia FOREIGN KEY(id_estadia)
        REFERENCES estadia(id_estadia)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_pagamento_forma CHECK (forma_pagamento IN ('PIX','DINHEIRO','CARTAO_CREDITO',
    'CARTAO_DEBITO')),
    CONSTRAINT ck_pagamento_valor CHECK(valor_pago >= 0)    
);